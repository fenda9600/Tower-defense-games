#!/usr/bin/env python3
"""Rasterise the Chinese characters used in src/*.js into 12 by 12 bitmaps and write src/71-cjk.js.

Needs Pillow and a CJK font. The default is Noto Sans CJK SC (SIL Open Font License 1.1); pass another font
file and face index as arguments if it lives elsewhere:  python3 tools/cjk.py [font.ttc] [index]
"""
import glob
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc'
INDEX = int(sys.argv[2]) if len(sys.argv) > 2 else 2
SIZES = (12, 16)


def used():
    chars = set()
    for path in sorted(glob.glob(os.path.join(ROOT, 'src', '*.js'))):
        if path.endswith('71-cjk.js'):
            continue
        for ch in open(path, encoding='utf-8').read():
            if ord(ch) >= 0x2E80:
                chars.add(ch)
    return sorted(chars)


def strike(chars, size):
    """One hex string of size-by-size bitmaps, one row after another, most significant bit on the left."""
    font = ImageFont.truetype(FONT, size, index=INDEX)
    digits = (size + 3) // 4
    raw, top, bottom = {}, 99, 0
    for ch in chars:
        im = Image.new('1', (size + 4, size + 10), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = '1'
        d.text((1, 2), ch, font=font, fill=1)
        raw[ch] = im
        box = im.getbbox()
        if box and 0x4E00 <= ord(ch) <= 0x9FFF:
            top, bottom = min(top, box[1]), max(bottom, box[3])
    clipped, out = 0, []
    for ch in chars:
        im = raw[ch]
        box = im.getbbox()
        x0, y0 = 1, top
        if box and box[2] - 1 > size:
            x0 = box[2] - size
        if box and bottom - top > size:
            # the common window is too tall: slide it to keep this glyph whole, or drop its emptier edge row
            ink = lambda y: sum(1 for x in range(im.width) if im.getpixel((x, y)))
            if box[3] - box[1] <= size:
                y0 = min(max(top, box[3] - size), box[1])
            else:
                y0 = box[1] + 1 if ink(box[1]) <= ink(box[3] - 1) else box[1]
                clipped += 1
        for r in range(size):
            bits = 0
            for c in range(size):
                x, y = x0 + c, y0 + r
                if 0 <= x < im.width and 0 <= y < im.height and im.getpixel((x, y)):
                    bits |= 1 << (size - 1 - c)
            out.append('%0*x' % (digits, bits))
    return ''.join(out), clipped


def main():
    chars = used()
    path = os.path.join(ROOT, 'src', '71-cjk.js')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/cjk.py from Noto Sans CJK SC at 12 px and 16 px (SIL Open Font License 1.1). Do not edit by hand.\n')
        f.write("PX.addWide('%s'" % ''.join(chars).replace('\\', '\\\\').replace("'", "\\'"))
        for size in SIZES:
            data, clipped = strike(chars, size)
            f.write(",\n  %d, '%s'" % (size, data))
            print('%d px: %d glyphs, %d lost one edge row' % (size, len(chars), clipped))
        f.write(');\n')
    print('->', path)


if __name__ == '__main__':
    main()
